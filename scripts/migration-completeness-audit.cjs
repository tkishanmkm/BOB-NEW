/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS is intentional for this standalone Node audit script. */
const fs = require("node:fs");
const path = require("node:path");

const root = process.cwd();
const publicDir = path.join(root, "public");
const manifestPath = path.join(root, "docs", "bob-world-asset-manifest.json");
const inventoryPath = path.join(root, "docs", "apk-screen-route-asset-inventory.md");
const outPath = path.join(root, "docs", "migration-completeness-audit.md");

const walk = (dir) => {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
};
const rel = (p) => path.relative(root, p).replace(/\\/g, "/");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8").replace(/^\uFEFF/, ""));
const allPublicFiles = walk(publicDir);
const sourceFiles = ["app", "components", "lib"].flatMap((d) => walk(path.join(root, d)))
  .filter((p) => /\.(tsx?|css|json)$/.test(p));
const sourceText = sourceFiles.map((p) => fs.readFileSync(p, "utf8")).join("\n");
const referencedPaths = new Set();
for (const match of sourceText.matchAll(/(?:["'(`])((?:\/assets\/)[^"'\s)`]+)/g)) referencedPaths.add(match[1].split(/[?#]/)[0]);
for (const match of sourceText.matchAll(/url\(\s*["']?([^"')]+)["']?\s*\)/g)) {
  const p = match[1].trim();
  if (p.startsWith("/assets/")) referencedPaths.add(p.split(/[?#]/)[0]);
}
const manifestMissing = manifest.filter((item) => {
  const relative = String(item.path || "").replace(/^\//, "").replace(/\//g, path.sep);
  return !fs.existsSync(path.join(publicDir, relative));
});
const refsFound = [...referencedPaths].filter((p) => fs.existsSync(path.join(publicDir, p.replace(/^\//, "").replace(/\//g, path.sep))));
const refsMissing = [...referencedPaths].filter((p) => !fs.existsSync(path.join(publicDir, p.replace(/^\//, "").replace(/\//g, path.sep))));
const pageFiles = walk(path.join(root, "app")).filter((p) => path.basename(p) === "page.tsx");
const featureFile = path.join(root, "app", "[feature]", "page.tsx");
const featureText = fs.existsSync(featureFile) ? fs.readFileSync(featureFile, "utf8") : "";
const featureKeys = new Set([...featureText.matchAll(/^\s{2}["']?([a-z0-9-]+)["']?\s*:\s*\{/gm)].map((m) => m[1]));
const inventory = fs.readFileSync(inventoryPath, "utf8");
const sourceRoutes = [...inventory.matchAll(/^\|\s*`(\/[^ `]*)`\s*\|\s*([^|]+)\|/gm)]
  .map((m) => ({ route: m[1], title: m[2].trim() }));
const extCounts = {};
let totalBytes = 0;
for (const file of allPublicFiles) {
  const ext = path.extname(file).toLowerCase() || "[no extension]";
  extCounts[ext] = (extCounts[ext] || 0) + 1;
  totalBytes += fs.statSync(file).size;
}
const routeRows = sourceRoutes.map(({ route, title }) => {
  const feature = route.slice(1);
  const pageFile = pageFiles.find((p) => {
    const relRoute = path.relative(path.join(root, "app"), path.dirname(p)).replace(/\\/g, "/");
    return (relRoute === "." ? "/" : "/" + relRoute) === route;
  });
  const pageText = pageFile ? fs.readFileSync(pageFile, "utf8").replace(/^\uFEFF/, "") : "";
  let status;
  let resolution;
  if (pageFile && /<FeaturePage\s+feature=/.test(pageText)) {
    status = "Generic feature page";
    resolution = "Route file delegates to the shared FeaturePage component; not an independent APK-matched screen";
  } else if (pageFile && /^\s*(?:["']use client["'];?\s*)?export\s*\{\s*default\s*\}\s*from\s*["'][^"']+["'];?\s*$/s.test(pageText)) {
    status = "Shared page alias";
    resolution = "Route re-exports another page component; not an independent screen";
  } else if (pageFile) {
    status = "Dedicated page file";
    resolution = "Direct page component exists; visual/functional parity still requires verification";
  } else if (featureKeys.has(feature)) {
    status = "Generic feature page";
    resolution = "Route handled by app/[feature]/page.tsx; not a faithful standalone APK layout";
  } else {
    status = "Needs route implementation";
    resolution = "No matching direct page or dynamic feature configuration found";
  }
  return { route, title, status, resolution };
});
const routeSummary = routeRows.reduce((acc, r) => (acc[r.status] = (acc[r.status] || 0) + 1, acc), {});
const lines = [
  "# BOB-NEW APK-to-Next.js Migration Completeness Audit",
  "",
  "> Generated by scripts/migration-completeness-audit.cjs from the current checkout. This is a static inventory, not a claim of visual parity or production approval.",
  "",
  "## Summary",
  "",
  `- Source routes listed in inventory: **${sourceRoutes.length}**`,
  `- Next.js page files (including dynamic route file): **${pageFiles.length}**`,
  `- Source routes with dedicated route file: **${routeSummary["Dedicated page file"] || 0}**`,
  `- Source routes served by generic feature page: **${routeSummary["Generic feature page"] || 0}**`,
  `- Source routes that alias another page: **${routeSummary["Shared page alias"] || 0}**`,
  `- Source routes without direct or dynamic configuration: **${routeSummary["Needs route implementation"] || 0}**`,
  `- Manifest records: **${manifest.length}**`,
  `- Manifest asset paths missing from public/: **${manifestMissing.length}**`,
  `- Files currently under public/: **${allPublicFiles.length}** (${(totalBytes / 1024 / 1024).toFixed(2)} MiB)`,
  `- Distinct statically detected /assets/ references in app/components/lib: **${referencedPaths.size}**`,
  `- Detected references that resolve to public/: **${refsFound.length}**`,
  `- Detected references that do not resolve to public/: **${refsMissing.length}**`,
  "",
  "## Source route mapping",
  "",
  "| Source route | Page / flow | Current static status | What this means |",
  "|---|---|---|---|",
  ...routeRows.map((r) => `| \`${r.route}\` | ${r.title.replace(/\|/g, "\\|")} | ${r.status} | ${r.resolution} |`),
  "",
  "## Public asset inventory by extension",
  "",
  "| Extension | Files |",
  "|---|---:|",
  ...Object.entries(extCounts).sort((a,b) => b[1]-a[1]).map(([ext,count]) => `| ${ext} | ${count} |`),
  "",
  "## Asset reconciliation",
  "",
  "The source manifest is compared against actual files under public/. A present file is not necessarily used in a screen. Static references are detected from app/, components/ and lib/; references created dynamically, assembled from string fragments, loaded from data, or embedded inside imported SVGs may not be detected.",
  "",
  "### Missing manifest files",
  "",
  ...(manifestMissing.length ? manifestMissing.map((x) => `- ${x.path} (expected ${x.bytes || "unknown"} bytes)`) : ["- None detected: every manifest path resolved to an existing file."]),
  "",
  "### Statically detected asset references",
  "",
  ...(refsFound.length ? refsFound.sort().map((x) => `- ${x}`) : ["- None detected."]),
  "",
  "### Unresolved statically detected asset references",
  "",
  ...(refsMissing.length ? refsMissing.sort().map((x) => `- ${x}`) : ["- None detected."]),
  "",
  "## Completion decision",
  "",
  "**NOT COMPLETE / NOT VISUALLY VERIFIED.** Route coverage is not the same as screen parity. Some routes are served by the generic feature page, and this static scan cannot verify original APK layout geometry, navigation, animations, responsive behavior, or native/SDK screens. Each route still needs comparison with authorized screenshots/runtime captures, and each asset needs a page mapping with confidence (confirmed/likely/unknown).",
  "",
  "## Required next work",
  "",
  "1. Review the per-route status table and replace generic feature placeholders with dedicated screen layouts and real demo interactions.",
  "2. Compare each screen against authorized APK screenshots/runtime captures; record visual differences and confidence.",
  "3. Reconcile source APK files with imported files using stable paths and hashes; inspect format conversions (especially Android XML/vector resources, which are not directly rendered by Next.js).",
  "4. Map relevant image/font/background assets to specific Next.js components; retain unrelated native/SDK resources in a reference archive rather than pretending they are usable UI assets.",
  "5. Test route navigation, mobile breakpoints, forms, local-only transfer simulation, and demo-watermarked statement/receipt outputs.",
  "6. Run typecheck, lint, tests, production build, and browser-based walkthrough before calling the migration complete.",
  ""
];
fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(JSON.stringify({
  report: rel(outPath),
  sourceRoutes: sourceRoutes.length,
  pageFiles: pageFiles.length,
  routeSummary,
  manifestEntries: manifest.length,
  manifestMissing: manifestMissing.length,
  publicFiles: allPublicFiles.length,
  publicMiB: +(totalBytes / 1024 / 1024).toFixed(2),
  detectedAssetReferences: referencedPaths.size,
  detectedReferencesFound: refsFound.length,
  detectedReferencesMissing: refsMissing.length,
  missingManifestSamples: manifestMissing.slice(0, 10).map((x) => x.path),
  missingReferenceSamples: refsMissing.slice(0, 10)
}, null, 2));
