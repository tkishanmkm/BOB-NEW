"use client";
import { useState } from "react";
import Link from "next/link";
import { Shell } from "@/components/app-shell";
import { ApkAssetIcon } from "@/components/apk-asset-map";

type ChatMessage = { id: number; from: "you" | "agent"; text: string };
type Style = "professional" | "friendly" | "concise";
const responses: Record<string, string> = {
  balance: "This prototype displays a sample balance calculated from its local opening balance and posted sample transactions. Open Account actions to review it.",
  statement: "You can review locally generated sample statements and date-filtered transaction analysis. These are not bank-issued records.",
  transfer: "Transfers in this prototype are simulations only. No payment instruction is sent and no funds move. Never use this demo to confirm a real payment.",
  account: "Account details shown here are local sample values. They are not verified against Bank of Baroda systems.",
  security: "Never share your PIN, password, OTP, CVV, or remote-access codes. Use only official, independently verified banking channels for real assistance.",
  default: "I can point you to the prototype's local screens, but I cannot access a bank account or contact a real support agent. Try asking about balance, statement, transfer, account details, or security."
};
const styles: Record<Style, { label: string; prefix: string }> = {
  professional: { label: "Professional", prefix: "Thank you for your question. " },
  friendly: { label: "Friendly", prefix: "Of course — here's a helpful note. " },
  concise: { label: "Concise", prefix: "" }
};
function answerFor(text: string, style: Style) {
  const q = text.toLowerCase();
  const key = q.includes("balance") ? "balance" : q.includes("statement") || q.includes("transaction") ? "statement" : q.includes("transfer") || q.includes("payment") ? "transfer" : q.includes("account") || q.includes("customer id") ? "account" : q.includes("security") || q.includes("pin") || q.includes("otp") || q.includes("password") ? "security" : "default";
  return styles[style].prefix + responses[key];
}
export default function AgentLiveChatPage() {
  const [style, setStyle] = useState<Style>("professional");
  const [draft, setDraft] = useState("");
  const [notice, setNotice] = useState("");
  const [messages, setMessages] = useState<ChatMessage[]>([{ id: 1, from: "agent", text: "Welcome to the demo assistant. I can guide you around this prototype, but I am not a bank employee and cannot access real accounts. Please do not share sensitive information." }]);
  function send(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    const text = draft.trim();
    if (!text) return;
    if (text.length > 500) { setNotice("Please keep messages under 500 characters."); return; }
    setMessages(old => [...old, { id: Date.now(), from: "you", text }, { id: Date.now() + 1, from: "agent", text: answerFor(text, style) }].slice(-40));
    setDraft("");
    setNotice("Demo response generated locally. No agent received your message.");
  }
  return <Shell>
    <div className="page-heading apk-page-heading"><ApkAssetIcon asset="help" size={32}/><div><p className="eyebrow">SUPPORT</p><h1>Agent live chat</h1><p className="muted">Interactive local assistant preview.</p></div></div>
    <div className="notice" role="note"><strong>Not a real support channel.</strong> Replies are generated by simple local topic matching. No bank employee receives messages, and no account lookup or bank action is performed.</div>
    <section className="card">
      <label className="field">Agent reply style<select value={style} onChange={e => setStyle(e.target.value as Style)}>{Object.entries(styles).map(([key,value])=><option key={key} value={key}>{value.label}</option>)}</select></label>
      <div className="chat-list" aria-live="polite">{messages.map(m=><article className="card" key={m.id}><strong>{m.from === "you" ? "You" : "Demo assistant"}</strong><p>{m.text}</p></article>)}</div>
      <form onSubmit={send}>
        <label className="field">Your question<textarea value={draft} maxLength={500} rows={3} required onChange={e=>setDraft(e.target.value)} placeholder="Try: How do I view my statement?"/></label>
        <div className="actions"><button type="submit">Send demo message</button><button type="button" className="btn secondary" onClick={()=>{setMessages([{id:1,from:"agent",text:"Welcome to the demo assistant. I can guide you around this prototype, but I am not a bank employee and cannot access real accounts. Please do not share sensitive information."}]);setNotice("Demo chat cleared.")}}>Reset chat</button></div>
      </form>
      {notice && <p className="muted" role="status">{notice}</p>}
      <div className="actions"><Link className="btn secondary" href="/help">Help centre</Link><Link className="btn secondary" href="/help-support">Local support inbox</Link><Link className="btn secondary" href="/security">Security guidance</Link></div>
    </section>
  </Shell>;
}
